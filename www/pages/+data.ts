// Read at build time from the repository: plugin headers, exported names and the version.
import { readFileSync, readdirSync } from 'node:fs'
import { join, resolve } from 'node:path'

export type Plugin = {
  name: string
  description: string
  requires: string[]
  generated: boolean
  commands: string[]
}

export type Data = { version: string; plugins: Plugin[]; omzTotal: number; testGroups: number }

const EXPORT = /^export\s+(?:alias|extern|def(?:\s+--[\w-]+)*)\s+("[^"]+"|'[^']+'|[^\s[=]+)/gm

export function data(): Data {
  // The build runs from www/; the repository is its parent.
  const repo = resolve(process.cwd(), '..')
  const dir = join(repo, 'plugins')
  const plugins = readdirSync(dir)
    .filter((f) => f.endsWith('.nu'))
    .sort()
    .map((file): Plugin => {
      const name = file.slice(0, -3)
      const source = readFileSync(join(dir, file), 'utf8')
      const header = (key: string) => source.match(new RegExp(`^# ${key}:[ \\t]*(.*)$`, 'm'))?.[1].trim() ?? ''
      const commands = [...source.matchAll(EXPORT)]
        .map((m) => m[1].replace(/^["']|["']$/g, ''))
        .map((n) => (n === 'main' ? name : n))
      return {
        name,
        description: header('description'),
        requires: header('requires').split(/\s+/).filter(Boolean),
        generated: source.includes('generated by tools/port-omz.py'),
        commands: [...new Set(commands)],
      }
    })
  const coverage = readFileSync(join(repo, 'COVERAGE.md'), 'utf8')
  const tests = readFileSync(join(repo, 'tests/run.nu'), 'utf8')
  return {
    version: readFileSync(join(repo, 'VERSION'), 'utf8').trim(),
    plugins,
    omzTotal: Number(coverage.match(/Oh My Zsh's (\d+) plugins/)?.[1] ?? 0),
    testGroups: tests.match(/^\s*\[[\w-]+, \{\|\| test-/gm)?.length ?? 0,
  }
}
